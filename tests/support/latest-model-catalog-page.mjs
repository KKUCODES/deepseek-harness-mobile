import assert from 'node:assert/strict';

/** 实际设置入口验收官方清单和隔离内置路由；目录来自原 Host，不发送模型请求。 */
export async function verifyModelCatalogManagement(page, verify) {
  const button = (root, name) => root.getByRole('button', { name, exact: true });
  const openSettings = async () => {
    await button(page, 'Remote 选项').click();
    await button(page, '电脑设置').click();
    await page.getByRole('combobox', { name: '设置页面', exact: true }).selectOption('models');
  };
  const save = async (region, name) => {
    await button(region, name).click();
    await region.getByText('已保存到电脑。', { exact: true }).waitFor();
  };
  const baseline = await verify('prepare');
  await openSettings();
  const official = page.getByRole('region', { name: '编辑 DeepSeek 模型清单', exact: true });
  await button(official, '编辑 DeepSeek 模型清单').click();
  const officialName = official.getByRole('textbox', { name: '模型名称 1', exact: true });
  await officialName.waitFor();
  assert.equal(await official.getByRole('textbox', { name: '模型 ID 1', exact: true }).inputValue(), baseline.officialId);
  assert.equal(await officialName.inputValue(), baseline.officialName);
  await officialName.fill('DSHM 官方模型验收');
  await official.locator('.remote-model-capabilities').first().locator('summary').click();
  await official.getByRole('combobox', { name: '输入类型 1', exact: true }).selectOption('text');
  await save(official, '保存模型清单');
  await verify('official-saved');
  await button(page, '关闭窗口').click();
  await page.locator('[data-composer-input]').click();
  await page.getByRole('button', { name: /^选择模型，当前 / }).click();
  const picker = page.getByRole('dialog', { name: '选择模型', exact: true });
  await button(picker, 'DSHM 官方模型验收').waitFor();
  await button(picker, '关闭窗口').click();
  await openSettings();
  await button(official, '编辑 DeepSeek 模型清单').click();
  await officialName.waitFor();
  assert.equal(await officialName.inputValue(), 'DSHM 官方模型验收');
  await official.locator('.remote-model-capabilities').first().locator('summary').click();
  assert.equal(await official.getByRole('combobox', { name: '输入类型 1', exact: true }).inputValue(), 'text');
  await button(official, '恢复默认模型清单').click();
  await save(official, '保存模型清单');
  assert.equal(await officialName.inputValue(), baseline.officialName);
  assert.equal(await button(official, '恢复默认模型清单').isEnabled(), false);
  await verify('official-restored');

  const providers = page.getByRole('region', { name: '其他模型提供方', exact: true });
  await button(providers, '其他模型提供方').click();
  const creation = providers.getByRole('region', { name: '新增模型提供方', exact: true });
  await button(creation, '新增模型提供方').click();
  await creation.getByRole('combobox', { name: /^提供方来源/ }).selectOption('catalog');
  await creation.getByRole('combobox', { name: /^选择内置提供方/ }).selectOption('openai');
  await creation.getByRole('textbox', { name: '显示名称（可选）', exact: true }).fill('DSHM 内置目录验收');
  await creation.getByRole('checkbox', { name: '使用 API Key，创建后在原生窗口配置', exact: true }).uncheck();
  await button(creation, '核对提供方').click();
  await button(creation, '确认新增').click();
  await button(creation, '查看提供方设置').waitFor();
  const catalog = await verify('builtin-created');
  await button(creation, '查看提供方设置').click();
  const form = providers.locator('.remote-provider-form');
  const overrides = form.getByRole('region', { name: '编辑内置模型覆盖', exact: true });
  await button(overrides, '编辑内置模型覆盖').click();
  await overrides.getByText('没有单独设置的用户覆盖。', { exact: true }).waitFor();
  const discover = async region => {
    await button(region, '获取可用模型').click();
    const candidates = region.locator(':scope > .remote-model-candidates');
    await candidates.waitFor();
    return candidates;
  };
  let candidates = await discover(overrides);
  assert.equal(await candidates.getByRole('checkbox').count(), catalog.count);
  await candidates.getByRole('checkbox').first().check();
  await button(candidates, '加入编辑草稿').click();
  const field = (region, name, index = 1) => region.getByRole('textbox', { name: `${name} ${index}`, exact: true });
  const firstId = await field(overrides, '模型 ID').inputValue();
  assert.equal(await field(overrides, '模型名称').inputValue(), '');
  assert.equal(await field(overrides, '上下文容量（Token）').inputValue(), '');
  await verify('builtin-draft', { ids: [firstId] });
  candidates = await discover(overrides);
  await candidates.getByRole('checkbox').first().check();
  await button(candidates, '加入编辑草稿').click();
  const secondId = await field(overrides, '模型 ID', 2).inputValue();
  await field(overrides, '模型名称').fill('DSHM 内置覆盖一');
  await field(overrides, '模型名称', 2).fill('DSHM 内置覆盖二');
  await field(overrides, '上下文容量（Token）', 2).fill('128001');
  await field(overrides, '输出容量（Token）', 2).fill('4097');
  const secondOverride = overrides.locator('.remote-provider-model-row').nth(1);
  await secondOverride.locator('.remote-model-capabilities').first().locator('summary').click();
  await secondOverride.getByRole('combobox', { name: '输入类型 2', exact: true }).selectOption('image,text');
  await secondOverride.getByRole('combobox', { name: '思考能力 2', exact: true }).selectOption('disabled');
  await secondOverride.locator('.remote-model-compat > summary').click();
  await secondOverride.getByRole('combobox', { name: '支持严格模式 2', exact: true }).selectOption('false');
  await save(overrides, '保存模型覆盖');
  await verify('builtin-overrides', { ids: [firstId, secondId] });
  await button(overrides.locator('.remote-provider-model-row').first(), '移除用户覆盖').click();
  await save(overrides, '保存模型覆盖');
  assert.equal(await field(overrides, '模型 ID').inputValue(), secondId);
  await verify('builtin-removed-one', { ids: [secondId] });
  await button(overrides, '恢复默认模型覆盖').click();
  await save(overrides, '保存模型覆盖');
  await overrides.getByText('没有单独设置的用户覆盖。', { exact: true }).waitFor();
  await verify('builtin-overrides-restored');
  const models = form.getByRole('region', { name: '编辑模型清单', exact: true });
  await button(models, '编辑模型清单').click();
  candidates = await discover(models);
  await candidates.getByRole('checkbox').first().check();
  await button(candidates, '加入编辑草稿').click();
  assert.equal(await field(models, '模型 ID').inputValue(), firstId);
  await field(models, '模型名称').fill('DSHM 内置清单');
  await save(models, '保存模型清单');
  await verify('builtin-list', { ids: [firstId] });
  await button(overrides, '重新读取模型覆盖').click();
  await overrides.getByText('当前使用自定义模型清单，请在模型清单中调整；恢复内置目录后可使用单个模型覆盖。', { exact: true }).waitFor();
  await overrides.getByText('正在处理…', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await button(overrides, '添加模型覆盖').isEnabled(), false);
  await button(models, '恢复默认模型清单').click();
  await save(models, '保存模型清单');
  await verify('builtin-list-restored');
  await button(overrides, '重新读取模型覆盖').click();
  await overrides.getByText('正在处理…', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await button(overrides, '添加模型覆盖').isEnabled(), true);
  const removal = form.getByRole('region', { name: '移除提供方', exact: true });
  await button(removal, '移除提供方').click();
  await button(removal.getByRole('group', { name: '确认移除提供方', exact: true }), '确认移除').click();
  await form.waitFor({ state: 'detached' });
  await verify('builtin-cleaned');
  await button(page, '关闭窗口').click();
}
