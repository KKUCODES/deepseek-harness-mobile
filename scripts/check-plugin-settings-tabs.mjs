import assert from 'node:assert/strict';

export async function checkPluginSettingsTabs(page) {
  await page.evaluate(async () => { window.fixture.settingsGrant(true); await window.fixture.enableSettingsTabs(); });
  const main = page.getByTestId('remote-workspace');
  await main.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await main.getByRole('button', { name: '电脑插件', exact: true }).click();
  await page.getByRole('button', { name: '插件设置', exact: true }).click({ timeout: 3000 });
  const first = page.getByTestId('settings-tab-one');
  await first.waitFor();
  assert.equal(await first.getAttribute('data-session'), 'none');
  await first.getByRole('button', { name: '计数 0', exact: true }).click();
  await page.getByRole('tab', { name: '扩展二', exact: true }).click();
  await page.getByTestId('settings-tab-two').waitFor();
  await page.getByRole('tab', { name: '扩展一', exact: true }).click();
  await first.getByRole('button', { name: '计数 1', exact: true }).waitFor();
  const width = await first.evaluate(n => n.getBoundingClientRect().width);
  assert.ok(width > 0 && width < 600 && width <= 420);
  await page.evaluate(() => window.fixture.settingsGrant(false));
  await first.waitFor({ state: 'detached' });
  await page.evaluate(() => window.fixture.settingsGrant(true));
  await first.getByRole('button', { name: '计数 0', exact: true }).waitFor();
  await page.evaluate(() => window.fixture.removeSettingsTabs());
  await first.waitFor({ state: 'detached' });
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.fixture.enableSettingsSections());
  await main.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await main.getByRole('button', { name: '电脑设置', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '电脑设置', exact: true });
  const select = settings.getByRole('combobox', { name: '设置页面', exact: true });
  await select.selectOption('fixture-section');
  const section = page.getByTestId('settings-section');
  await section.waitFor();
  assert.equal(await section.getAttribute('data-session'), 'none');
  await section.getByRole('textbox', { name: '插件设置草稿', exact: true }).fill('keep draft');
  await select.selectOption('models');
  await page.evaluate(() => window.fixture.closeSettingsSection());
  await settings.getByRole('spinbutton', { name: '单次回复上限（Token）', exact: true }).waitFor();
  await select.selectOption('fixture-section');
  assert.equal(await section.getByRole('textbox', { name: '插件设置草稿', exact: true }).inputValue(), 'keep draft');
  const sectionWidth = await section.evaluate(n => n.getBoundingClientRect().width);
  assert.ok(sectionWidth > 0 && sectionWidth <= 420);
  await section.getByRole('button', { name: '完成设置', exact: true }).click();
  await settings.waitFor({ state: 'detached' });
  await main.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await main.getByRole('button', { name: '电脑设置', exact: true }).click();
  await select.selectOption('fixture-section');
  await page.evaluate(() => window.fixture.removeSettingsSections());
  await section.waitFor({ state: 'detached' });
  await page.evaluate(() => window.fixture.closeSettingsSection());
  await settings.getByRole('spinbutton', { name: '单次回复上限（Token）', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.fixture.settingsGrant(false));
  return { ownEntry: true, rootScope: true, switchKeepsState: true, scaledWidth: width, revokedUnmounts: true, unloaded: true };
}
