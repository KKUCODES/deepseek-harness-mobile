import assert from 'node:assert/strict';

export async function checkKeyStateSync(page) {
  await page.evaluate(() => window.fixture.settingsGrant(true));
  await page.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await page.getByRole('button', { name: '电脑设置', exact: true }).click();
  const key = page.getByRole('region', { name: '电脑 DeepSeek Key', exact: true });
  await key.getByText('已配置', { exact: true }).waitFor();
  const settings = page.getByRole('dialog', { name: '电脑设置', exact: true });
  const limit = settings.getByRole('spinbutton', { name: '单次回复上限（Token）', exact: true });
  await page.evaluate(() => window.fixture.settingsPush(2048));
  await page.waitForFunction(() => document.querySelector('#computer-maxTokens')?.value === '2048');
  await limit.fill('3072');
  await page.evaluate(() => window.fixture.settingsPush(4096));
  await settings.getByText('电脑设置已变化。你的修改已保留，请重新读取设置后核对。', { exact: true }).waitFor();
  assert.equal(await limit.inputValue(), '3072');
  assert.equal(await settings.getByRole('button', { name: '保存到电脑', exact: true }).isDisabled(), true);
  await settings.getByRole('button', { name: '重新读取设置', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#computer-maxTokens')?.value === '4096');
  await page.evaluate(() => window.fixture.holdSettingsRead());
  await page.evaluate(() => window.fixture.settingsPush(5120));
  await settings.getByRole('button', { name: '正在处理…', exact: true }).waitFor();
  await page.evaluate(() => { window.fixture.settingsPush(6144); window.fixture.releaseSettingsRead(); });
  await page.waitForFunction(() => document.querySelector('#computer-maxTokens')?.value === '6144');
  // 本地校验失败没有发送请求，也没有使快照失效；修正输入后应可继续保存。
  await limit.fill('');
  await settings.getByRole('button', { name: '保存到电脑', exact: true }).click();
  await settings.getByText('请输入有效的设置值。', { exact: true }).waitFor();
  assert.equal(await limit.inputValue(), '');
  await limit.fill('7168');
  assert.equal(await settings.getByRole('button', { name: '保存到电脑', exact: true }).isDisabled(), false);
  await page.evaluate(() => window.fixture.settingsConflict());
  await settings.getByRole('button', { name: '保存到电脑', exact: true }).click();
  await settings.getByText('电脑设置已变化或页面已过期，请重新读取后再修改。', { exact: true }).waitFor();
  assert.equal(await limit.count(), 1, '保存失败后表单应继续显示待核对草稿');
  assert.equal(await limit.inputValue(), '7168');
  assert.equal(await settings.getByRole('button', { name: '保存到电脑', exact: true }).isDisabled(), true);
  await page.evaluate(() => window.fixture.failSettingsRead());
  await settings.getByRole('button', { name: '重新读取设置', exact: true }).click();
  await settings.getByText('电脑尚未提供这些设置，请确认对应插件已启用。', { exact: true }).waitFor();
  assert.equal(await limit.count(), 1, '重新读取失败也不能隐藏仍未核对的草稿');
  assert.equal(await limit.inputValue(), '7168');
  assert.equal(await settings.getByRole('button', { name: '保存到电脑', exact: true }).isDisabled(), true);
  await settings.getByRole('button', { name: '重新读取设置', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#computer-maxTokens')?.value === '6144');
  const before = await page.evaluate(() => window.fixture.keyNativeCalls().length);
  await page.evaluate(() => window.fixture.modelListEnable());
  const models = settings.getByRole('region', { name: '编辑 DeepSeek 模型清单', exact: true });
  await models.getByRole('button', { name: '编辑 DeepSeek 模型清单', exact: true }).click();
  const modelName = models.getByRole('textbox', { name: '模型名称 1', exact: true });
  await modelName.waitFor();
  const waitName = value => page.waitForFunction(v => document.querySelector('[aria-label="模型名称 1"]')?.value === v, value);
  await page.evaluate(() => window.fixture.modelListPush('Updated model'));
  await waitName('Updated model');
  await modelName.fill('Phone draft');
  await page.evaluate(() => window.fixture.modelListPush('New desktop model'));
  await models.getByText('电脑设置已变化。你的修改已保留，请重新读取设置后核对。', { exact: true }).waitFor();
  assert.equal(await modelName.inputValue(), 'Phone draft');
  assert.equal(await models.getByRole('button', { name: '保存模型清单', exact: true }).isDisabled(), true);
  await models.getByRole('button', { name: '重新读取模型清单', exact: true }).click();
  await waitName('New desktop model');
  await page.evaluate(() => { window.fixture.holdModelListRead(); window.fixture.modelListPush('Obsolete'); });
  await models.getByText('正在处理…', { exact: true }).waitFor();
  await page.evaluate(() => { window.fixture.modelListPush('Latest'); window.fixture.releaseModelListRead(); });
  await waitName('Latest');
  await models.getByRole('button', { name: '编辑 DeepSeek 模型清单', exact: true }).click();
  const reads = await page.evaluate(() => window.fixture.modelListReads());
  await page.evaluate(() => window.fixture.modelListPush('Closed'));
  assert.equal(await page.evaluate(() => window.fixture.modelListReads()), reads);
  await page.evaluate(() => window.fixture.keyConfigured(false));
  await key.getByText('尚未配置', { exact: true }).waitFor({ timeout: 3000 });
  await page.evaluate(() => window.fixture.holdKeyRead());
  await key.getByRole('button', { name: '重新读取 Key 状态', exact: true }).click();
  await page.evaluate(() => window.fixture.keyConfigured(true));
  await key.getByText('尚未配置', { exact: true }).waitFor({ state: 'hidden' });
  await page.evaluate(() => window.fixture.releaseKeyRead());
  await key.getByText('已配置', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.fixture.keyNativeCalls().length), before, '失效事件不能触发原生写入');
  await page.evaluate(() => window.fixture.holdKeyNative());
  await key.getByRole('button', { name: '管理电脑 Key', exact: true }).click();
  await page.evaluate(() => window.fixture.keyConfigured(false));
  assert.equal(await key.getByRole('button', { name: '管理电脑 Key', exact: true }).isDisabled(), true);
  await page.evaluate(() => window.fixture.releaseKeyNative());
  await key.getByText('尚未配置', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.fixture.keyNativeCalls().length), before + 1, '原生操作中事件只合并重读，不重复写入');
  await page.evaluate(() => window.fixture.keyConfigured(true));
  await key.getByText('已配置', { exact: true }).waitFor();
  await page.evaluate(() => window.fixture.settingsGrant(false));
  await key.waitFor({ state: 'detached' });
  await page.getByRole('dialog', { name: '电脑设置', exact: true }).getByRole('button', { name: '关闭窗口', exact: true }).click();
  return { pushedState: true, scalarSettingsSync: true, scalarDraftPreserved: true, failedSaveDraftVisible: true, failedSaveRequiresReload: true, scalarStaleReadDiscarded: true, staleReadDiscarded: true, rereadAfterInflightChange: true, noAutomaticNativeWrite: true, nativeInflightCoalesced: true, revoked: true };
}
