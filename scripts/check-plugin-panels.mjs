import assert from 'node:assert/strict';

export async function checkPluginPanels(page) {
  await page.evaluate(() => window.fixture.enablePanels());
  await page.evaluate(() => window.fixture.beginPendingPanelSelection('one'));
  assert.equal(await page.getByRole('button', { name: '查看请求', exact: true }).isDisabled(), true, '待审批入口也必须等待会话引用');
  await page.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  const pendingButton = page.getByRole('button', { name: '插件面板', exact: true });
  // 真正点击实际入口，修复前会抛同一 no session surface 错误；禁用后不调控制器。
  if (await pendingButton.isEnabled()) await pendingButton.click();
  assert.equal(await pendingButton.isDisabled(), true, '会话引用未就绪时不能打开面板');
  await page.evaluate(() => window.fixture.releasePendingPanelSelection());
  await pendingButton.click();
  const pendingPanel = page.getByRole('region', { name: '插件面板', exact: true });
  await pendingPanel.getByRole('button', { name: '返回聊天', exact: true }).click();
  await page.evaluate(() => window.fixture.select('two'));
  const draft = page.getByRole('textbox', { name: '消息', exact: true });
  await draft.fill('面板测试草稿');
  await page.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await page.getByRole('button', { name: '插件面板', exact: true }).click();
  const dialog = page.getByRole('region', { name: '插件面板', exact: true });
  await dialog.getByRole('button', { name: '测试面板', exact: true }).click();
  assert.equal(await page.getByTestId('remote-workspace').evaluate(element => element.inert), true);
  assert.equal(await page.getByTestId('fixture-connect-page').evaluate(element => element.inert), false);
  const content = page.getByTestId('fixture-panel');
  await content.getByText('two:initial', { exact: true }).waitFor();
  await content.getByRole('button', { name: '打开插件弹窗', exact: true }).click();
  const modal = page.getByRole('dialog', { name: '原插件弹窗', exact: true });
  await modal.getByRole('textbox', { name: '插件弹窗输入', exact: true }).fill('手机弹窗输入', { timeout: 3000 });
  await modal.getByRole('button', { name: '弹窗菜单', exact: true }).click();
  await page.evaluate(() => window.dshmHandleBack());
  await page.getByRole('menuitem', { name: '填入菜单值', exact: true }).waitFor({ state: 'detached' });
  assert.ok(await modal.isVisible(), '返回先关闭弹窗菜单，保留弹窗');
  await page.evaluate(() => window.dshmHandleBack());
  await modal.waitFor({ state: 'detached' });
  assert.ok(await dialog.isVisible(), '返回先关闭插件弹窗，保留面板');
  await content.getByRole('button', { name: '打开插件弹窗', exact: true }).click();
  assert.equal(await modal.getByRole('textbox', { name: '插件弹窗输入', exact: true }).inputValue(), '手机弹窗输入');
  await modal.getByRole('button', { name: '弹窗菜单', exact: true }).click();
  await page.getByRole('menuitem', { name: '填入菜单值', exact: true }).click();
  assert.equal(await modal.getByRole('textbox', { name: '插件弹窗输入', exact: true }).inputValue(), 'menu-value');
  await modal.getByRole('button', { name: '关闭插件弹窗', exact: true }).click();
  await dialog.getByRole('button', { name: '面板操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '插件菜单操作', exact: true }).click();
  await content.getByText('two:menu-action', { exact: true }).waitFor();
  await page.getByRole('menuitem', { name: '插件菜单操作', exact: true }).waitFor({ state: 'detached' });
  await dialog.getByRole('button', { name: '面板操作', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('menuitem', { name: '插件菜单操作', exact: true }).waitFor({ state: 'detached' });
  assert.ok(await dialog.isVisible());
  await content.getByRole('button', { name: '计数 0', exact: true }).click();
  await page.evaluate(() => window.fixture.openPanel('updated'));
  await content.getByText('two:updated', { exact: true }).waitFor();
  await content.getByRole('button', { name: '计数 1', exact: true }).waitFor();
  const width = await content.evaluate(element => element.getBoundingClientRect().width);
  assert.ok(width <= 375 && width > 250, `外层缩放 ${width}`);
  await content.getByRole('button', { name: '选择其他面板', exact: true }).click();
  await dialog.locator('nav').getByRole('button', { name: '测试面板', exact: true }).click();
  await content.getByRole('button', { name: '计数 1', exact: true }).waitFor();
  await dialog.getByRole('button', { name: '返回聊天', exact: true }).click();
  assert.equal(await page.getByTestId('remote-workspace').evaluate(element => element.inert), false);
  await dialog.waitFor({ state: 'hidden' });
  await page.evaluate(() => window.fixture.openPanel('updated'));
  await content.getByRole('button', { name: '计数 1', exact: true }).waitFor();
  await page.evaluate(() => window.fixture.panelFile());
  await page.getByRole('dialog', { name: '文件预览', exact: true }).getByText('Mobile panel file contents', { exact: true }).waitFor();
  await page.evaluate(() => window.dshmHandleBack());
  await page.evaluate(() => window.fixture.openPanel('updated'));
  await content.getByRole('button', { name: '计数 1', exact: true }).waitFor();
  await page.evaluate(() => window.fixture.closePanel());
  await content.waitFor({ state: 'detached' });
  assert.equal((await page.evaluate(() => window.fixture.panelAborts())).length, 1);
  await dialog.getByRole('button', { name: '返回聊天', exact: true }).click();
  assert.equal(await draft.innerText(), '面板测试草稿');
  await page.evaluate(() => window.fixture.panelFile());
  const file = page.getByRole('dialog', { name: '文件预览', exact: true });
  await file.getByText('Mobile panel file contents', { exact: true }).waitFor();
  await page.evaluate(() => window.dshmHandleBack());
  await file.waitFor({ state: 'detached' });
  await page.evaluate(() => window.fixture.openPanel('two-session'));
  await page.evaluate(() => window.fixture.select('one'));
  await dialog.waitFor({ state: 'hidden' });
  await page.evaluate(() => window.fixture.openPanel('one-session'));
  await content.getByText('one:one-session', { exact: true }).waitFor();
  await page.evaluate(() => window.fixture.select('two'));
  await content.getByText('two:two-session', { exact: true }).waitFor();
  await page.evaluate(() => window.fixture.disablePanels());
  await dialog.getByText('此面板的插件暂不可用。', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: '打开面板', exact: true }).click();
  assert.equal(await dialog.locator('[data-sidebar-right-guide-entry="fixture-panel"]').count(), 0);
  await dialog.getByRole('button', { name: '返回聊天', exact: true }).click();
  assert.equal(await draft.innerText(), '面板测试草稿');
  return { pendingSessionMenuAndNoticeGated: true, readySessionOpensImmediately: true, ownWindow: true, navigationParams: true, retainedTabState: true, outerScaling: width, originalCloseSignal: true, fileBridge: true, androidBack: true, sessionIsolation: true, uninstallFallback: true, draftPreserved: true,
    originalModalInteractive: true, nestedMenuAndModalBack: true, tabMenuExtension: true, escapeMenuOnly: true, backgroundInertRestored: true };
}
