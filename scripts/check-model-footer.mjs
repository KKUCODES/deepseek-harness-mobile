import assert from 'node:assert/strict';

export async function checkModelFooter(page) {
  await page.evaluate(() => { window.fixture.settingsGrant(true); return window.fixture.enableModelFooter(); });
  const main = page.getByTestId('remote-workspace');
  await main.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await main.getByRole('button', { name: '电脑设置', exact: true }).click();
  const footer = page.getByTestId('model-footer');
  await footer.waitFor({ timeout: 5000 });
  const card = page.getByTestId('model-provider-card');
  await card.waitFor();
  assert.equal(await card.getAttribute('data-session'), 'none');
  assert.equal(await card.getAttribute('data-provider'), 'deepseek-official');
  assert.equal(await card.getAttribute('data-configured'), 'true');
  assert.equal(await card.getAttribute('data-key'), 'true');
  const draft = card.getByRole('textbox', { name: '提供方扩展草稿', exact: true });
  await draft.fill('keep provider extension draft');
  await page.evaluate(() => window.fixture.keyConfigured(false));
  await page.waitForFunction(() => document.querySelector('[data-testid="model-provider-card"]')?.dataset.key === 'false');
  assert.equal(await draft.inputValue(), 'keep provider extension draft');
  await page.evaluate(() => { window.fixture.holdProviderCardRead(); window.fixture.keyConfigured(false); });
  await card.waitFor({ state: 'hidden' });
  assert.equal(await card.count(), 1, 'Pending refresh retains the mounted plugin without showing stale owner');
  await page.evaluate(() => window.fixture.releaseProviderCardRead(true));
  const retry = page.getByRole('button', { name: '重新读取设置', exact: true }).last();
  await retry.waitFor();
  assert.equal(await card.isVisible(), false);
  await retry.click();
  await card.waitFor();
  assert.equal(await draft.inputValue(), 'keep provider extension draft');
  await page.evaluate(() => window.fixture.keyConfigured(true));
  await page.waitForFunction(() => document.querySelector('[data-testid="model-provider-card"]')?.dataset.key === 'true');
  assert.equal(await draft.inputValue(), 'keep provider extension draft');
  assert.equal(await footer.count(), 1);
  assert.equal(await footer.getAttribute('data-session'), 'none');
  await footer.getByRole('button', { name: '设置扩展 0', exact: true }).click();
  await footer.getByRole('button', { name: '设置扩展 1', exact: true }).waitFor();
  const width = await footer.evaluate(node => node.getBoundingClientRect().width);
  assert.ok(width < 600 && width <= 420, `插件外层应适配手机宽度，实际 ${width}`);
  await page.evaluate(() => window.fixture.settingsGrant(false));
  await footer.waitFor({ state: 'detached' });
  await card.waitFor({ state: 'detached' });
  await page.evaluate(() => window.fixture.settingsGrant(true));
  await footer.getByRole('button', { name: '设置扩展 0', exact: true }).waitFor();
  await page.evaluate(() => window.fixture.removeModelFooter());
  await footer.waitFor({ state: 'detached' });
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.fixture.settingsGrant(false));
  return { settingsEntry: true, providerCard: true, refreshKeepsDraft: true, failedRefreshKeepsDraft: true, pendingOwnerHidden: true, rootScope: true, interactive: true, scaledWidth: width, revokedHides: true, unload: true };
}
