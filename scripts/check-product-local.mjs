import assert from 'node:assert/strict';

// 所有写操作均经过正式页面；只新建测试草稿，并将插件和外观设置恢复。
export async function checkProductLocal(page) {
  const button = name => page.getByRole('button', { name, exact: true });
  const editor = () => page.getByRole('textbox', { name: '消息', exact: true });
  const navigate = async name => { await button('打开侧边抽屉').click(); await button(name).click(); };
  const backPlugins = async () => { await button('返回').click(); await button('返回').click(); };
  await button('新聊天').click();
  await editor().fill('/总');
  await page.getByRole('option', { name: '总结', exact: true }).click();
  assert.equal(await editor().inputValue(), '请总结下面的内容：');
  await editor().fill('DSHM_PLUGIN_UI_TEST 草稿');
  await navigate('插件');
  await page.locator('.plugin-row').filter({ hasText: '输入提示词' }).click();
  await button('卸载').click(); await button('确认卸载').click();
  await button('安装').waitFor();
  await backPlugins();
  await editor().fill('/总');
  assert.equal(await page.getByRole('option', { name: '总结', exact: true }).count(), 0);
  await editor().fill('卸载后仍可输入');
  await navigate('插件'); await button('安装插件').click();
  await page.locator('.plugin-row').filter({ hasText: '输入提示词' }).click();
  await button('安装').click(); await button('卸载').waitFor();
  await button('返回').click(); await button('返回').click(); await button('返回').click();
  assert.equal(await editor().inputValue(), '卸载后仍可输入');
  await editor().fill('/总');
  await page.getByRole('option', { name: '总结', exact: true }).click();
  assert.equal(await editor().inputValue(), '请总结下面的内容：');
  await editor().fill('DSHM_PLUGIN_UI_TEST 草稿保留');
  await navigate('设置');
  await page.getByRole('button', { name: /^外观与语言/ }).click();
  const originalTheme = await page.getByRole('button', { name: /^主题 / }).innerText();
  await page.getByRole('button', { name: /^主题 / }).click();
  await page.getByRole('button', { name: '深色', exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.dsThemeSource === 'dark');
  await page.getByRole('button', { name: /^语言 / }).click();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await button('Back to settings').waitFor();
  await button('Back to settings').click(); await button('Close settings').click();
  await button('Open sidebar').click();
  await button('Plugins').click();
  assert.equal(await page.getByRole('button', { name: /^Input prompts/ }).count(), 1);
  await button('Back').click(); await button('Open sidebar').click(); await button('Settings').click();
  await page.getByRole('button', { name: /^Appearance and language/ }).click();
  await page.getByRole('button', { name: /^Language / }).click();
  await page.getByRole('button', { name: '简体中文', exact: true }).click();
  await page.getByRole('button', { name: /^主题 / }).click();
  const restoreTheme = ['跟随系统', '浅色', '深色'].find(label => originalTheme.includes(label));
  assert.ok(restoreTheme); await page.getByRole('button', { name: restoreTheme, exact: true }).click();
  await button('返回设置首页').click(); await button('退出设置').click();
  assert.equal(await editor().inputValue(), 'DSHM_PLUGIN_UI_TEST 草稿保留');
  await editor().click();
  const geometry = await page.evaluate(() => ({ width: innerWidth, bodyWidth: document.body.scrollWidth, rootWidth: document.documentElement.scrollWidth }));
  assert.ok(geometry.bodyWidth <= geometry.width + 1 && geometry.rootWidth <= geometry.width + 1);
  await page.reload();
  await editor().waitFor();
  assert.equal(await editor().inputValue(), '');
  await button('打开侧边抽屉').click();
  await page.locator('.history-row').first().click();
  assert.equal(await editor().inputValue(), 'DSHM_PLUGIN_UI_TEST 草稿保留');
  await editor().fill('/总');
  await page.getByRole('option', { name: '总结', exact: true }).click();
  await editor().fill('DSHM_PLUGIN_UI_TEST 草稿保留');
  return { inputPluginActualUninstallInstall: true, draftPreserved: true, themeApplied: true, globalEnglishChinese: true, reload: true, noHorizontalOverflow: geometry };
}
