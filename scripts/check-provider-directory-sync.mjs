import assert from 'node:assert/strict';

export async function checkProviderDirectorySync(page) {
  await page.evaluate(() => {
    window.fixture.settingsGrant(true);
    window.fixture.providerDirectory([{ provider: 'alpha', name: 'Alpha' }]);
  });
  await page.getByRole('button', { name: 'Remote 选项', exact: true }).click();
  await page.getByRole('button', { name: '电脑设置', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '电脑设置', exact: true });
  const directory = panel.getByRole('region', { name: '其他模型提供方', exact: true });
  await directory.getByRole('button', { name: '其他模型提供方', exact: true }).click();
  const picker = directory.getByRole('combobox', { name: '模型提供方', exact: true });
  const creation = directory.getByRole('region', { name: '新增模型提供方', exact: true });
  await creation.getByRole('button', { name: '新增模型提供方', exact: true }).click();
  await creation.getByLabel('提供方来源').selectOption('custom');
  await creation.getByLabel('提供方标识', { exact: true }).fill('unsaved-new-provider');
  await creation.getByLabel('服务地址', { exact: true }).fill('https://example.invalid/v1');
  await picker.selectOption('alpha');
  await picker.selectOption('');
  assert.equal(await creation.getByLabel('提供方标识', { exact: true }).count(), 1, 'Returning to creation must retain its draft form');
  assert.equal(await creation.getByLabel('提供方标识', { exact: true }).inputValue(), 'unsaved-new-provider');
  assert.equal(await creation.getByLabel('服务地址', { exact: true }).inputValue(), 'https://example.invalid/v1');
  await creation.getByRole('button', { name: '取消', exact: true }).click();
  await picker.selectOption('alpha');
  const draft = directory.locator('.remote-provider-form:visible').getByLabel('提供方名称', { exact: true });
  await draft.fill('Unsaved phone draft');
  const form = directory.locator('.remote-provider-form:visible');
  await page.evaluate(() => window.fixture.providerSettingsReadFailure(true));
  await form.getByRole('button', { name: '重新读取设置', exact: true }).click();
  await form.getByText('电脑尚未提供这些设置，请确认对应插件已启用。', { exact: true }).waitFor();
  assert.equal(await draft.count(), 1, 'Failed provider reread must retain the form');
  assert.equal(await draft.inputValue(), 'Unsaved phone draft');
  assert.equal(await form.getByRole('button', { name: '保存到电脑', exact: true }).isDisabled(), true);
  await page.evaluate(() => window.fixture.providerSettingsReadFailure(false));
  await form.getByRole('button', { name: '重新读取设置', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.remote-provider-form:not([hidden]) input[type="text"]')?.value === 'Alpha');
  await draft.fill('Unsaved phone draft');
  await page.evaluate(() => window.fixture.providerDirectory([{ provider: 'alpha', name: 'Renamed' }, { provider: 'beta', name: 'Beta' }]));
  await picker.locator('option[value="beta"]').waitFor({ state: 'attached', timeout: 3000 });
  assert.equal(await picker.locator('option[value="alpha"]').textContent(), 'Renamed');
  assert.equal(await picker.inputValue(), 'alpha');
  assert.equal(await draft.inputValue(), 'Unsaved phone draft');
  await picker.selectOption('beta');
  await draft.fill('Beta phone draft');
  await picker.selectOption('alpha');
  assert.equal(await draft.inputValue(), 'Unsaved phone draft', 'Switching providers must preserve each draft');
  await picker.selectOption('beta');
  assert.equal(await draft.inputValue(), 'Beta phone draft');
  await picker.selectOption('alpha');
  await page.evaluate(() => { window.fixture.providerListFailure(true); window.fixture.providerDirectory([{ provider: 'alpha', name: 'Renamed' }]); });
  await directory.getByText('电脑尚未提供这些设置，请确认对应插件已启用。', { exact: true }).waitFor();
  assert.equal(await draft.inputValue(), 'Unsaved phone draft');
  await page.evaluate(() => { window.fixture.providerListFailure(false); window.fixture.holdProviderList(); });
  await directory.getByRole('button', { name: '刷新提供方', exact: true }).click();
  await page.evaluate(() => window.fixture.providerDirectory([{ provider: 'alpha', name: 'Newest' }, { provider: 'gamma', name: 'Gamma' }]));
  await page.evaluate(() => window.fixture.releaseProviderList());
  await picker.locator('option[value="gamma"]').waitFor({ state: 'attached' });
  assert.equal(await picker.locator('option[value="alpha"]').textContent(), 'Newest');
  assert.equal(await draft.inputValue(), 'Unsaved phone draft');
  await page.evaluate(() => window.fixture.providerDirectory([{ provider: 'gamma', name: 'Gamma' }]));
  await draft.waitFor({ state: 'detached' });
  assert.equal(await picker.inputValue(), '');
  await directory.getByRole('button', { name: '其他模型提供方', exact: true }).click();
  const reads = await page.evaluate(() => window.fixture.providerListReads());
  await page.evaluate(() => window.fixture.providerDirectory([]));
  assert.equal(await page.evaluate(() => window.fixture.providerListReads()), reads, 'Closed directory must not refresh');
  await page.evaluate(() => window.fixture.providerCreationRows());
  await directory.getByRole('button', { name: '其他模型提供方', exact: true }).click();
  await creation.getByRole('button', { name: '新增模型提供方', exact: true }).click();
  await creation.getByLabel('提供方标识', { exact: true }).fill('structured-models');
  await creation.getByLabel('服务地址', { exact: true }).fill('https://example.invalid/v1');
  await creation.getByLabel('模型 ID 1', { exact: true }).fill('vision-model');
  await creation.getByLabel('模型名称 1', { exact: true }).fill('Vision');
  await creation.getByLabel('上下文容量（Token） 1', { exact: true }).fill('128K');
  await creation.getByLabel('输出容量（Token） 1', { exact: true }).fill('0');
  assert.equal(await creation.getByRole('button', { name: '核对提供方', exact: true }).isDisabled(), true);
  await creation.getByLabel('输出容量（Token） 1', { exact: true }).fill('8K');
  await creation.getByText('输入类型', { exact: true }).first().click();
  await creation.getByLabel('输入类型 1', { exact: true }).selectOption('image,text');
  await creation.getByRole('button', { name: '核对提供方', exact: true }).click();
  await creation.getByRole('button', { name: '确认新增', exact: true }).click();
  await creation.getByRole('button', { name: '查看提供方设置', exact: true }).waitFor();
  const writes = await page.evaluate(() => window.fixture.providerCreationWrites());
  assert.deepEqual(writes.at(-1).models, [{ id: 'vision-model', name: 'Vision', contextWindow: 128000, maxTokens: 8000, input: ['image', 'text'] }]);
  await panel.getByRole('button', { name: '关闭窗口', exact: true }).click();
  await page.evaluate(() => window.fixture.settingsGrant(false));
  return { structuredCreationPayload: true, oldHostCreationFallback: true, externalAddRenameRemove: true, draftPreserved: true, switchingPreservesIndependentDrafts: true, failedRefreshRetainsForm: true, staleReadSuperseded: true, closedDoesNotRead: true };
}
